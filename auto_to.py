# Replay parsing
# ============================================================

def get_player_nickname(player):
    """
    Try to extract the Slippi player nickname.

    peppi versions differ somewhat, so this deliberately
    checks several possible attributes.
    """

    possible_values = [
        getattr(player, "nametag", None),
        getattr(player, "name", None),
        getattr(player, "nickname", None),
    ]

    for value in possible_values:
        if value:
            return str(value).strip()

    # Some versions expose metadata through a dict-like object.
    try:
        if isinstance(player, dict):
            for key in (
                "nametag",
                "name",
                "nickname",
            ):
                value = player.get(key)
                if value:
                    return str(value).strip()
    except Exception:
        pass

    return None


def extract_replay_result(filepath):
    """
    Read the final game state from an SLP replay.

    Returns:

        {
            "players": [
                {
                    "nickname": ...,
                    "port": ...,
                    "stocks": ...,
                    "percent": ...
                }
            ]
        }

    """

    print(
        f"[MATCH SCANNER] Reading replay: {filepath}",
        flush=True
    )

    game = read_slippi(
        filepath,
        skip_frames=False
    )

    if not hasattr(game, "start"):
        raise RuntimeError(
            "Replay does not contain start data"
        )

    if not hasattr(game.start, "players"):
        raise RuntimeError(
            "Replay does not contain player data"
        )

    if not hasattr(game, "frames"):
        raise RuntimeError(
            "Replay does not contain frame data"
        )

    players = game.start.players

    if not players:
        raise RuntimeError(
            "Replay has no players"
        )

    player_ports = [
        p.port
        for p in players
    ]

    min_port = min(player_ports)

    results = []

    for player in players:

        port_key = (
            0
            if player.port == min_port
            else 1
        )

        stocks = None
        percent = None

        try:
            port_data = game.frames.ports[
                port_key
            ]

            stocks = (
                port_data
                .leader
                .post
                .stocks[-1]
                .as_py()
            )

            percent = (
                port_data
                .leader
                .post
                .percent[-1]
                .as_py()
            )

        except Exception as e:

            print(
                f"[MATCH SCANNER] Could not read "
                f"final state for port {player.port}: {e}",
                flush=True
            )

        nickname = get_player_nickname(
            player
        )

        results.append({
            "nickname": nickname,
            "port": player.port,
            "stocks": stocks,
            "percent": percent,
        })

    return {
        "players": results
    }


# ============================================================
# Match player identification
# ============================================================

def identify_match_players(
    replay_result,
    session1,
    session2
):
    """
    Determine which replay player belongs to each session.

    First tries to match Slippi nametags.

    If names aren't available, falls back to port order.

    This fallback is only safe if your check-in system
    consistently assigns the players to P1/P2.
    """

    replay_players = replay_result["players"]

    nickname1 = normalize_name(
        session1["nickname"]
    )

    nickname2 = normalize_name(
        session2["nickname"]
    )

    # --------------------------------------------------------
    # Best case: Slippi exposes player nicknames.
    # --------------------------------------------------------

    if all(
        player.get("nickname")
        for player in replay_players
    ):

        for p1 in replay_players:

            for p2 in replay_players:

                if p1 is p2:
                    continue

                if (
                    normalize_name(
                        p1["nickname"]
                    ) == nickname1
                    and
                    normalize_name(
                        p2["nickname"]
                    ) == nickname2
                ):

                    return p1, p2

    # --------------------------------------------------------
    # Fallback: sort by port.
    # --------------------------------------------------------

    replay_players = sorted(
        replay_players,
        key=lambda x: x["port"]
    )

    if len(replay_players) >= 2:

        return (
            replay_players[0],
            replay_players[1],
        )

    return None, None


# ============================================================
# Determine winner
# ============================================================

def determine_winner(
    player1,
    player2
):
    """
    Winner rules:

    1. More stocks wins.
    2. If stocks are tied, lower percent wins.
    """

    stocks1 = player1.get("stocks")
    stocks2 = player2.get("stocks")

    percent1 = player1.get("percent")
    percent2 = player2.get("percent")

    if stocks1 is None or stocks2 is None:
        raise RuntimeError(
            "Could not determine final stock counts"
        )

    # --------------------------------------------------------
    # Stocks determine the winner.
    # --------------------------------------------------------

    if stocks1 > stocks2:
        return 1

    if stocks2 > stocks1:
        return 2

    # --------------------------------------------------------
    # Stocks tied.
    #
    # Lowest percent wins.
    # --------------------------------------------------------

    if percent1 is None or percent2 is None:
        raise RuntimeError(
            "Stocks were tied but final percent "
            "could not be determined"
        )

    if percent1 < percent2:
        return 1

    if percent2 < percent1:
        return 2

    # --------------------------------------------------------
    # Completely tied.
    # --------------------------------------------------------

    return 0


# ============================================================
# Match ID
# ============================================================

def make_match_key(
    replay,
    session1,
    session2
):
    """
    Generate a stable ID so the same replay isn't reported
    repeatedly every 60 seconds.
    """

    players = sorted([
        (
            normalize_name(session1["nickname"]),
            str(
                session1.get("entrant_id")
                or ""
            )
        ),
        (
            normalize_name(session2["nickname"]),
            str(
                session2.get("entrant_id")
                or ""
            )
        ),
    ])

    return "|".join([
        os.path.abspath(
            replay["filepath"]
        ),
        players[0][0],
        players[0][1],
        players[1][0],
        players[1][1],
    ])


# ============================================================
# Find overlapping player sessions
# ============================================================

def find_overlapping_sessions(
    sessions
):
    """
    A match requires two different players on the same
    console with overlapping check-in/check-out windows.
    """

    matches = []

    for i in range(len(sessions)):

        session1 = sessions[i]

        for j in range(i + 1, len(sessions)):

            session2 = sessions[j]

            # Must be different players.
            if (
                normalize_name(
                    session1["nickname"]
                )
                ==
                normalize_name(
                    session2["nickname"]
                )
            ):
                continue

            # Must be the same console.
            if (
                normalize_name(
                    session1["console_name"]
                )
                !=
                normalize_name(
                    session2["console_name"]
                )
            ):
                continue

            # ------------------------------------------------
            # Check whether their sessions overlap.
            # ------------------------------------------------

            overlap_start = max(
                session1["start"],
                session2["start"]
            )

            overlap_end = min(
                session1["end"],
                session2["end"]
            )

            if overlap_start >= overlap_end:
                continue

            matches.append({
                "player1": session1,
                "player2": session2,
                "overlap_start": overlap_start,
                "overlap_end": overlap_end,
            })

    return matches


# ============================================================
# Process replay matches
# ============================================================

def process_replay_matches():
    """
    Scan the entire replay/check-in directory and report any
    newly completed matches.
    """

    print(
        "[MATCH SCANNER] Starting scan...",
        flush=True
    )

    files = scan_session_files()

    print(
        "[MATCH SCANNER] Found "
        f"{len(files['checkins'])} check-ins, "
        f"{len(files['checkouts'])} check-outs, "
        f"{len(files['warmups'])} warmups.",
        flush=True
    )

    # Warmups are deliberately collected above but aren't used
    # to report tournament matches. They remain available if
    # you later want warmup-specific logic.

    sessions = pair_sessions(
        files["checkins"],
        files["checkouts"]
    )

    print(
        f"[MATCH SCANNER] Found "
        f"{len(sessions)} completed player sessions.",
        flush=True
    )

    overlapping_matches = find_overlapping_sessions(
        sessions
    )

    print(
        f"[MATCH SCANNER] Found "
        f"{len(overlapping_matches)} possible matches.",
        flush=True
    )

    for possible_match in overlapping_matches:

        session1 = possible_match["player1"]
        session2 = possible_match["player2"]

        # ----------------------------------------------------
        # Find replays for player 1.
        #
        # Because the sessions overlap, the replay must also
        # be inside the overlap period.
        # ----------------------------------------------------

        replay_candidates = find_replays_for_session(
            session1
        )

        for replay in replay_candidates:

            replay_time = replay["timestamp"]

            if replay_time < possible_match["overlap_start"]:
                continue

            if replay_time > possible_match["overlap_end"]:
                continue

            match_key = make_match_key(
                replay,
                session1,
                session2
            )

            with processed_matches_lock:
                already_processed = (
                    match_key
                    in processed_matches
                )

            if already_processed:
                continue

            print(
                "\n[MATCH SCANNER] ============================",
                flush=True
            )

            print(
                f"[MATCH SCANNER] Replay: "
                f"{replay['filename']}",
                flush=True
            )

            print(
                f"[MATCH SCANNER] "
                f"{session1['nickname']} vs "
                f"{session2['nickname']}",
                flush=True
            )

            try:

                # --------------------------------------------
                # Parse replay.
                # --------------------------------------------

                replay_result = extract_replay_result(
                    replay["filepath"]
                )

                replay_p1, replay_p2 = identify_match_players(
                    replay_result,
                    session1,
                    session2
                )

                if replay_p1 is None or replay_p2 is None:
                    raise RuntimeError(
                        "Could not identify both players "
                        "in the replay"
                    )

                # --------------------------------------------
                # Determine winner.
                # --------------------------------------------

                winner = determine_winner(
                    replay_p1,
                    replay_p2
                )

                if winner == 0:
                    print(
                        "[MATCH SCANNER] Match is completely tied. "
                        "No result will be reported.",
                        flush=True
                    )

                    # Mark it processed so we don't repeatedly
                    # print it every minute.
                    with processed_matches_lock:
                        processed_matches.add(
                            match_key
                        )

                    save_processed_matches()

                    continue

                if winner == 1:

                    winner_session = session1
                    loser_session = session2
                    winner_replay = replay_p1
                    loser_replay = replay_p2

                else:

                    winner_session = session2
                    loser_session = session1
                    winner_replay = replay_p2
                    loser_replay = replay_p1

                # --------------------------------------------
                # Log result.
                # --------------------------------------------

                print(
                    "[MATCH SCANNER] RESULT",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] Winner: "
                    f"{winner_session['nickname']}",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] "
                    f"Winner stocks: "
                    f"{winner_replay['stocks']}",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] "
                    f"Winner percent: "
                    f"{winner_replay['percent']}",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] "
                    f"Loser: "
                    f"{loser_session['nickname']}",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] "
                    f"Loser stocks: "
                    f"{loser_replay['stocks']}",
                    flush=True
                )

                print(
                    f"[MATCH SCANNER] "
                    f"Loser percent: "
                    f"{loser_replay['percent']}",
                    flush=True
                )

                # --------------------------------------------
                # Report to start.gg.
                # --------------------------------------------

                if (
                    not winner_session.get("entrant_id")
                    or
                    not loser_session.get("entrant_id")
                ):

                    raise RuntimeError(
                        "Missing entrant ID for one or both players"
                    )

                report_result = process_request(
                    winner_session["nickname"],
                    loser_session["nickname"],
                    1,
                    0,
                    winner_session["entrant_id"],
                    loser_session["entrant_id"],
                )

                print(
                    f"[MATCH SCANNER] start.gg result: "
                    f"{report_result}",
                    flush=True
                )

                # --------------------------------------------
                # Mark processed.
                # --------------------------------------------

                with processed_matches_lock:
                    processed_matches.add(
                        match_key
                    )

                save_processed_matches()

            except Exception as e:

                print(
                    f"[MATCH SCANNER] Error processing "
                    f"{replay['filename']}: {e}",
                    flush=True
                )

            print(
                "[MATCH SCANNER] ============================\n",
                flush=True
            )


# ============================================================
# Background scanner
# ============================================================

def replay_scanner_worker():

    print(
        "[MATCH SCANNER] Background scanner started.",
        flush=True
    )

    while True:

        try:
            process_replay_matches()

        except Exception as e:

            print(
                f"[MATCH SCANNER] Scanner error: {e}",
                flush=True
            )

        time.sleep(
            SCAN_INTERVAL
        )


# ============================================================
# start.gg GraphQL helper
# ============================================================

def startgg_request(
    query,
    variables=None
):
    """
    Execute a GraphQL request against start.gg.
    """

    headers = {
        "Authorization": (
            f"Bearer {STARTGG_BEARER}"
        ),
        "Content-Type": "application/json",
        "Accept": "application/json",
    }

    payload = {
        "query": query,
        "variables": variables or {},
    }

    response = requests.post(
        STARTGG_API_URL,
        headers=headers,
        json=payload,
        timeout=30,
    )

    response.raise_for_status()

    result = response.json()

    if "errors" in result:

        messages = []

        for error in result["errors"]:

            messages.append(
                error.get(
                    "message",
                    str(error)
                )
            )

        raise RuntimeError(
            "start.gg API error: "
            + "; ".join(messages)
        )

    return result["data"]


