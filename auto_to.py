def parse_timestamp(timestamp):
    """
    Parse timestamps generated by your check-in/check-out code.

    Expected:
        20260827T214500

    Also accepts a few common variants.
    """

    if not timestamp:
        return None

    timestamp = str(timestamp).strip()

    formats = [
        "%Y%m%dT%H%M%S",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S",
        "%Y-%m-%dT%H:%M:%S.%f",
    ]

    for fmt in formats:
        try:
            return datetime.strptime(timestamp, fmt)
        except ValueError:
            pass

    return None


def get_json_timestamp(data, filepath):
    """
    Get timestamp from JSON.

    Falls back to the file modification time.
    """

    timestamp = data.get("timestamp")

    parsed = parse_timestamp(timestamp)

    if parsed:
        return parsed

    try:
        return datetime.fromtimestamp(
            os.path.getmtime(filepath)
        )
    except Exception:
        return None


def get_console_name(data):
    """
    Support both:

        console_name
        consolename
    """

    return (
        data.get("console_name")
        or data.get("consolename")
        or data.get("console")
    )


def get_nickname(data):
    return (
        data.get("nickname")
        or data.get("name")
        or ""
    ).strip()


def get_entrant_id(data):
    value = (
        data.get("eid")
        or data.get("entrantid")
        or data.get("entrant_id")
    )

    if value is None:
        return None

    return str(value)


def get_replay_console_name(filepath):
    """
    Your replay filenames appear to follow:

        something.console_name.slp

    Example:

        Game.Station1.slp
    """

    filename = os.path.basename(filepath)

    parts = filename.rsplit(".", 2)

    if (
        len(parts) == 3
        and parts[2].lower() == "slp"
        and parts[1]
    ):
        return parts[1]

    return None


def get_replay_time(filepath):
    """
    Prefer filesystem creation time if available.

    Fall back to modification time.
    """

    try:
        stat = os.stat(filepath)

        # Linux generally does not expose creation time.
        birthtime = getattr(stat, "st_birthtime", None)

        if birthtime:
            return datetime.fromtimestamp(birthtime)

        return datetime.fromtimestamp(stat.st_mtime)

    except Exception:
        return None


def normalize_name(value):
    if value is None:
        return ""

    return str(value).strip().casefold()


# ============================================================
# Check-in / checkout / warmup scanning
# ============================================================

def scan_session_files():
    """
    Find all checkin, checkout, and warmup JSON files.

    Returns:

        {
            "checkins": [...],
            "checkouts": [...],
            "warmups": [...]
        }
    """

    result = {
        "checkins": [],
        "checkouts": [],
        "warmups": [],
    }

    if not os.path.isdir(REPLAY_FOLDER):
        print(
            f"[MATCH SCANNER] Replay folder does not exist: "
            f"{REPLAY_FOLDER}",
            flush=True
        )
        return result

    for filename in os.listdir(REPLAY_FOLDER):

        if not filename.lower().endswith(".json"):
            continue

        filepath = os.path.join(
            REPLAY_FOLDER,
            filename
        )

        try:
            with open(
                filepath,
                "r",
                encoding="utf-8"
            ) as f:
                data = json.load(f)

        except Exception as e:
            print(
                f"[MATCH SCANNER] Could not read {filepath}: {e}",
                flush=True
            )
            continue

        if not isinstance(data, dict):
            continue

        timestamp = get_json_timestamp(
            data,
            filepath
        )

        if timestamp is None:
            continue

        console_name = get_console_name(data)
        nickname = get_nickname(data)
        entrant_id = get_entrant_id(data)

        if not console_name or not nickname:
            continue

        entry = {
            "filepath": filepath,
            "filename": filename,
            "timestamp": timestamp,
            "console_name": console_name,
            "nickname": nickname,
            "entrant_id": entrant_id,
            "data": data,
        }

        filename_lower = filename.lower()

        if "checkin" in filename_lower:
            result["checkins"].append(entry)

        elif "checkout" in filename_lower:
            result["checkouts"].append(entry)

        elif "warmup" in filename_lower:
            result["warmups"].append(entry)

    result["checkins"].sort(
        key=lambda x: x["timestamp"]
    )

    result["checkouts"].sort(
        key=lambda x: x["timestamp"]
    )

    result["warmups"].sort(
        key=lambda x: x["timestamp"]
    )

    return result


# ============================================================
# Pair check-in -> checkout
# ============================================================

def pair_sessions(checkins, checkouts):
    """
    Pair each check-in with the next chronological checkout
    having the same console + nickname.

    A checkout cannot be reused.
    """

    used_checkouts = set()
    sessions = []

    for checkin in checkins:

        candidates = []

        for checkout_index, checkout in enumerate(
            checkouts
        ):

            if checkout_index in used_checkouts:
                continue

            if normalize_name(
                checkout["console_name"]
            ) != normalize_name(
                checkin["console_name"]
            ):
                continue

            if normalize_name(
                checkout["nickname"]
            ) != normalize_name(
                checkin["nickname"]
            ):
                continue

            if checkout["timestamp"] <= checkin["timestamp"]:
                continue

            candidates.append(
                (
                    checkout["timestamp"],
                    checkout_index,
                    checkout
                )
            )

        if not candidates:
            continue

        candidates.sort(
            key=lambda x: x[0]
        )

        _, checkout_index, checkout = candidates[0]

        used_checkouts.add(checkout_index)

        sessions.append({
            "checkin": checkin,
            "checkout": checkout,
            "console_name": checkin["console_name"],
            "nickname": checkin["nickname"],
            "entrant_id": (
                checkin["entrant_id"]
                or checkout["entrant_id"]
            ),
            "start": checkin["timestamp"],
            "end": checkout["timestamp"],
        })

    return sessions


# ============================================================
# Replay discovery
# ============================================================

def find_replays_for_session(session):
    """
    Find SLP files on the same console whose timestamps fall
    inside the player's check-in -> checkout window.
    """

    results = []

    console_name = normalize_name(
        session["console_name"]
    )

    if not os.path.isdir(REPLAY_FOLDER):
        return results

    for filename in os.listdir(REPLAY_FOLDER):

        if not filename.lower().endswith(".slp"):
            continue

        filepath = os.path.join(
            REPLAY_FOLDER,
            filename
        )

        replay_console = get_replay_console_name(
            filepath
        )

        if not replay_console:
            continue

        if normalize_name(
            replay_console
        ) != console_name:
            continue

        replay_time = get_replay_time(filepath)

        if replay_time is None:
            continue

        if replay_time < session["start"]:
            continue

        if replay_time > session["end"]:
            continue

        results.append({
            "filepath": filepath,
            "filename": filename,
            "timestamp": replay_time,
        })

    results.sort(
        key=lambda x: x["timestamp"]
    )

    return results


