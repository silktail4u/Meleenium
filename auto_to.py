def get_event_id_from_slug(slug):

    query = """
    query GetEvent($slug: String!) {
        event(slug: $slug) {
            id
            name
        }
    }
    """

    data = startgg_request(
        query,
        {
            "slug": slug
        }
    )

    event = data.get("event")

    if not event:
        raise RuntimeError(
            f"Could not find start.gg event: {slug}"
        )

    return str(event["id"])


