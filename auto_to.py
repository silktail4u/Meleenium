processed_matches_lock = threading.Lock()


def load_processed_matches():
    if not os.path.exists(PROCESSED_MATCHES_FILE):
        return set()

    try:
        with open(
            PROCESSED_MATCHES_FILE,
            "r",
            encoding="utf-8"
        ) as f:
            data = json.load(f)

        if isinstance(data, list):
            return set(data)

        return set()

    except Exception as e:
        print(
            f"[MATCH SCANNER] Failed to load "
            f"{PROCESSED_MATCHES_FILE}: {e}",
            flush=True
        )

        return set()


processed_matches = load_processed_matches()


def save_processed_matches():
    try:
        with processed_matches_lock:
            data = sorted(processed_matches)

        with open(
            PROCESSED_MATCHES_FILE,
            "w",
            encoding="utf-8"
        ) as f:
            json.dump(data, f, indent=2)

    except Exception as e:
        print(
            f"[MATCH SCANNER] Failed to save processed matches: {e}",
            flush=True
        )


